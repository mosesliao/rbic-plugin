"""The rbic-init block of policy.csv: where the compiled onboarding rules live.

    # ---- BEGIN rbic init (generated; edit onboarding/*.json and re-run rbic-init compile) ----
    p, hr_staff, employees.name, read
    ...
    # ---- END rbic init ----

`rbic-init compile` replaces only the lines between (and including) the
two markers; every line outside them (hand-written rules, comments, the
master chatbot's section) is kept byte for byte. The master chatbot never
removes or edits a line inside the block (PolicyAdmin refuses), nor a
hand-written copy outside it of a rule the block generates (the block's
copy is authoritative), so the onboarding sources stay the single source
of truth for what it holds.

Markers are matched as whole lines (surrounding whitespace and the line
end ignored). A line that merely starts like a marker, a duplicated
marker, an END before its BEGIN or a BEGIN without END makes the file
"malformed": both the compiler and the master bot then refuse to touch
policy.csv until a human fixes it (fail closed - a half-recognized block
could otherwise swallow or expose hand-written rules).

No imports from rbic.admin (admin imports this module).
"""

from typing import Optional

BEGIN_MARKER = ("# ---- BEGIN rbic init (generated; edit onboarding/*.json "
                "and re-run rbic-init compile) ----")
END_MARKER = "# ---- END rbic init ----"
_BEGIN_PREFIX = "# ---- BEGIN rbic init"
_END_PREFIX = "# ---- END rbic init"
GENERATED_RULE_MESSAGE = (
    "this rule is generated by rbic-init from onboarding/*.json; change the "
    "catalog/roles there and run rbic-init compile")
GENERATED_DUPLICATE_MESSAGE = (
    "this rule is also generated by rbic-init: the copy inside the rbic-init "
    "block is authoritative, so removing this hand-written copy outside it "
    "would change nothing; to change what the generated rule grants or "
    "limits, edit onboarding/catalog.json / roles.json and run rbic-init "
    "compile")


class BlockError(ValueError):
    """policy.csv's rbic-init markers are malformed."""


def split_lines(text: str) -> list:
    """Split on LF only, keeping line ends (exactly the lines Casbin's file
    adapter sees; str.splitlines() would also split on form feeds etc.)."""
    parts = text.split("\n")
    out = [p + "\n" for p in parts[:-1]]
    if parts[-1]:
        out.append(parts[-1])
    return out


def _marker(line: str) -> Optional[str]:
    """"begin"/"end" for an exact marker line; raise for a near miss."""
    s = line.strip()
    if s == BEGIN_MARKER:
        return "begin"
    if s == END_MARKER:
        return "end"
    compact = " ".join(s.split())
    if compact.startswith(_BEGIN_PREFIX) or compact.startswith(_END_PREFIX):
        raise BlockError(f"malformed rbic-init marker line {s!r} (expected "
                         f"exactly {BEGIN_MARKER!r} or {END_MARKER!r})")
    return None


def find_block(text: str) -> Optional[tuple]:
    """(begin, end) line indexes (inclusive, over split_lines) of the
    rbic-init block, or None when the file has none. Raises BlockError
    for malformed, duplicated, unbalanced or out-of-order markers."""
    begins, ends = [], []
    for i, line in enumerate(split_lines(text)):
        kind = _marker(line)
        if kind == "begin":
            begins.append(i + 1)
        elif kind == "end":
            ends.append(i + 1)
    if not begins and not ends:
        return None
    if len(begins) != 1 or len(ends) != 1:
        raise BlockError(
            f"policy.csv must hold at most one rbic-init block (found "
            f"{len(begins)} BEGIN and {len(ends)} END marker(s), lines "
            + ", ".join(map(str, sorted(begins + ends))) + ")")
    if ends[0] < begins[0]:
        raise BlockError(f"rbic-init END marker (line {ends[0]}) comes before "
                         f"its BEGIN marker (line {begins[0]})")
    return begins[0] - 1, ends[0] - 1


def block_line_indexes(text: str) -> set:
    """Indexes (over split_lines) of the lines inside the block, markers
    included; empty when there is no block."""
    span = find_block(text)
    return set(range(span[0], span[1] + 1)) if span else set()


def outside_lines(text: str) -> list:
    """The lines outside the block (all lines when there is none)."""
    inside = block_line_indexes(text)
    return [l for i, l in enumerate(split_lines(text)) if i not in inside]


def _newline(text: str) -> str:
    return "\r\n" if "\r\n" in text else "\n"


def replace_block(text: str, body: list, *, before_header: Optional[str] = None
                  ) -> str:
    """`text` with its block replaced by BEGIN + `body` (lines without line
    ends) + END. Without a block, the new one goes right before the line
    equal to `before_header` (the master chatbot's section) if there is
    one, else at the end. Lines outside the block are kept byte for byte
    (a file whose last line has no line end gets one before a new block)."""
    nl = _newline(text)
    block = [BEGIN_MARKER + nl, *(b + nl for b in body), END_MARKER + nl]
    lines = split_lines(text)
    span = find_block(text)
    if span is not None:
        begin, end = span
        return "".join(lines[:begin] + block + lines[end + 1:])
    if before_header is not None:
        for i, line in enumerate(lines):
            if line.rstrip("\r\n") == before_header:
                return "".join(lines[:i] + block + lines[i:])
    head = "".join(lines)
    if head and not head.endswith("\n"):
        head += nl  # the only change outside the block: a final line end
    return head + "".join(block)
